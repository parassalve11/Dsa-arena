// Regenerates src/data/problems/index.js with an explicit loader for every
// problem file, so the bundler code-splits them one chunk per problem.
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { catalog } from "../src/data/catalog.js";
import { PROBLEMS_DIR } from "./lib/runners.js";

const files = new Set(readdirSync(PROBLEMS_DIR).filter((f) => f.endsWith(".js") && f !== "index.js"));
const present = catalog.filter((p) => files.has(`${p.slug}.js`));
const lines = present.map(
  (p) => `  ${JSON.stringify(p.slug)}: () => Promise.all([import("./${p.slug}.js"), import("../expected/${p.slug}.json")]),`
);
const out = `// Generated by \`npm run gen-index\`. Do not edit by hand.
import { catalog, bySlug } from "../catalog.js";
import { buildProblem } from "../../lib/problem.js";

const loaders = {
${lines.join("\n")}
};

// Metadata for every available problem, in sheet order (for the dashboard).
export const problems = catalog.filter((p) => p.slug in loaders);

export function hasProblem(slug) {
  return slug in loaders;
}

export async function getProblem(slug) {
  if (!(slug in loaders)) return null;
  const [mod, expected] = await loaders[slug]();
  return buildProblem(bySlug[slug], mod.default, expected.default);
}
`;
writeFileSync(path.join(PROBLEMS_DIR, "index.js"), out);
console.log(`index.js written with ${present.length} problems`);
